import json
import re
import logging
from typing import Dict, Any, List
from app.agents.base import BaseAgent

logger = logging.getLogger("AI-Travel-Guide-Supervisor")

SUPERVISOR_SYSTEM_PROMPT = """
You are the Supervisor Agent for a multi-agent AI Travel Guide System.
Your job is to understand the user's travel request, decide which specialized agents are needed, extract parameters, and compile final answers.

Available specialized agents:
- destination: For places, attractions, best time, things to do.
- weather: For live weather and current conditions.
- transport: For routes and how to reach.
- hotel: For stay areas and hotel suggestions.
- food: For local food and restaurants.
- budget: For cost estimation.
- itinerary: For day-wise planning.
- booking_link: For stay/transport search links and direct booking options.
- safety: For safety, packing, local rules, and travel warnings.

When analyzing the user's query, you MUST return a valid JSON object matching the schema below.
CRITICAL: Do NOT wrap the JSON in markdown code blocks. Return ONLY the raw JSON string.

JSON Schema:
{
  "is_planning": boolean, // true if the user wants to plan a trip (fully or partially)
  "is_complete_plan": boolean, // true if the user wants a full comprehensive trip plan
  "missing_details": [string], // e.g. ["source", "days"] if planning but details are missing. If destination is missing, definitely add it.
  "follow_up_question": string, // Ask ONLY the necessary follow-up question if critical details are missing to plan the trip. Set to empty string if no follow-up is needed.
  "agents_to_run": [string], // List of agents to invoke.
  "extracted_params": {
    "source": string or null,
    "destination": string or null,
    "days": integer or null,
    "people": integer or null,
    "budget": string or null,
    "interests": string or null,
    "travel_style": string or null, // "budget", "medium", or "luxury"
    "food_preference": string or null
  }
}
"""

MERGE_SYSTEM_PROMPT = """
You are the Supervisor Agent for a multi-agent AI Travel Guide System.
Your job is to merge all specialized agents' outputs into a single, cohesive, complete, and practical travel plan.

Rules:
- Never say booking is confirmed.
- Never create fake PNR, ticket ID, hotel confirmation ID, or payment confirmation.
- Always say prices and availability should be verified before booking.
- If a link cannot be found, provide a safe search link instead.
- Keep the final answer structured and user-friendly.

You MUST structure the final output with these exact headings:

# Ready-to-Go Travel Plan

## 1. Trip Summary
[Brief description of the trip details, source, destination, style, and interests]

## 2. Weather
[Weather overview and climate details]

## 3. Best Transport Options
[Compare transit options, approximate travel times/costs, and include direct booking/search links generated by Transport and Booking agents]

## 4. Stay Recommendations
[Stay areas, hostel/hotel zones, and direct booking/search links generated by Hotel and Booking agents]

## 5. Places to Visit
[Main sights and tourist attractions]

## 6. Food Suggestions
[Local dishes, street food hubs, vegetarian highlights]

## 7. Day-wise Itinerary
[Day-by-day morning, afternoon, evening planning]

## 8. Budget Estimate
[Programmatic budget cost breakdown]

## 9. Booking Links
[Consolidate all transport search and hotel booking/search links here]

## 10. Packing Checklist
[Necessary clothing, gear, and items]

## 11. Safety Tips
[General precautions, restrictions, weather notices]

## 12. Final Checklist Before Booking
[Include exact checklist bullet points]:
- Verify train/bus/flight timing
- Check hotel reviews
- Confirm cancellation policy
- Check weather one day before travel
- Keep ID proof
- Save offline maps
- Keep emergency cash
"""

class SupervisorAgent(BaseAgent):
    def __init__(self):
        super().__init__(name="supervisor", system_prompt=SUPERVISOR_SYSTEM_PROMPT)

    def analyze_query(self, user_message: str, endpoint: str = "/chat") -> Dict[str, Any]:
        """
        Parses the user query using the LLM to extract parameters and plan routing.
        """
        from app.tracing import create_trace, active_trace_var
        
        # Ensure trace is created if not already active
        trace = active_trace_var.get()
        if not trace:
            trace = create_trace(
                name="travel_plan_request",
                input=user_message,
                metadata={
                    "workflow": "multi_agent_travel_guide",
                    "model": OPENROUTER_MODEL,
                    "endpoint_used": endpoint
                }
            )

        with self.trace_agent({"user_message": user_message}, user_query=user_message) as tc:
            try:
                response_text = self.generate_response(
                    f"Please analyze the following query and return JSON format:\nQuery: {user_message}"
                )
                
                cleaned = response_text.strip()
                if cleaned.startswith("```"):
                    cleaned = re.sub(r"^```[a-zA-Z]*\n", "", cleaned)
                    cleaned = re.sub(r"\n```$", "", cleaned)
                    cleaned = cleaned.strip()

                parsed = json.loads(cleaned)
                if "agents_to_run" in parsed and isinstance(parsed["agents_to_run"], list):
                    parsed["agents_to_run"] = [a.lower().strip() for a in parsed["agents_to_run"]]
                
                # Update trace with extracted metadata and routing
                if trace:
                    params = parsed.get("extracted_params", {})
                    trace.update(
                        metadata={
                            "workflow": "multi_agent_travel_guide",
                            "agents_used": parsed.get("agents_to_run", []),
                            "model": OPENROUTER_MODEL,
                            "source": params.get("source"),
                            "destination": params.get("destination"),
                            "days": params.get("days"),
                            "people": params.get("people"),
                            "interests": params.get("interests"),
                            "travel_style": params.get("travel_style"),
                            "food_preference": params.get("food_preference"),
                            "endpoint_used": endpoint
                        }
                    )
                
                tc.set_output(parsed)
                return parsed
            except Exception as e:
                # Fallback if parsing fails
                fallback_data = {
                    "is_planning": True,
                    "is_complete_plan": True,
                    "missing_details": [],
                    "follow_up_question": "",
                    "agents_to_run": ["destination", "weather", "transport", "hotel", "food", "budget", "itinerary", "booking_link", "safety"],
                    "extracted_params": {
                        "source": "Delhi",
                        "destination": "Jaipur",
                        "days": 3,
                        "people": 2,
                        "budget": "15000",
                        "interests": None,
                        "travel_style": "budget",
                        "food_preference": None
                    }
                }
                tc.set_error(f"Error parsing supervisor analysis: {e}")
                tc.set_output(fallback_data)
                return fallback_data

    def merge_responses(self, params: Dict[str, Any], agent_outputs: Dict[str, str], agents_used: List[str]) -> str:
        """
        Compiles and formats the responses from all active agents into a unified output.
        """
        from app.tracing import create_span, end_span
        
        # Trace the merge step
        fm_span = create_span(
            name="final_merge", 
            input={"params": params, "agents_used": agents_used}
        )
        
        context_str = ""
        for agent_name, output in agent_outputs.items():
            context_str += f"=== {agent_name.upper()} AGENT OUTPUT ===\n{output}\n\n"

        prompt = (
            f"Merge the outputs below into a unified response for a trip to {params.get('destination')} from {params.get('source')}.\n"
            f"Trip Parameters: Days: {params.get('days')}, People: {params.get('people')}, Budget: {params.get('budget')}, Style: {params.get('travel_style')}, Interests: {params.get('interests')}, Food preference: {params.get('food_preference')}\n\n"
            f"Specialized Agent Outputs:\n{context_str}\n"
            f"In your final response, list the agents used: {', '.join(agents_used)}."
        )

        try:
            from langchain_core.messages import SystemMessage, HumanMessage
            messages = [
                SystemMessage(content=MERGE_SYSTEM_PROMPT),
                HumanMessage(content=prompt)
            ]
            response = self.llm.invoke(messages)
            res = response.content
            
            logger.info("Final response generated.")
            if fm_span:
                end_span(fm_span, output=res)
            return res
        except Exception as e:
            error_str = str(e).lower()
            if fm_span:
                fm_span[1].update(level="ERROR", status_message=str(e))
                end_span(fm_span, output=f"Error during merge step: {str(e)}")
                
            if "rate limit" in error_str or "429" in error_str or "unavailable" in error_str:
                return (
                    "The free OpenRouter model may be rate-limited or unavailable. "
                    "Try again later or set another model in OPENROUTER_MODEL."
                )
            return f"Error during merge step: {str(e)}"

    async def run_stream(self, params: Dict[str, Any], endpoint: str = "/chat") -> AsyncGenerator[str, None]:
        """
        Executes a streaming response containing Server-Sent Events (SSE).
        Traces each agent execution using Langfuse, yielding progress details,
        and streams the final merged response progressively.
        """
        import asyncio
        from typing import AsyncGenerator
        from app.streaming import format_sse, create_progress_event, stream_text_chunks, stream_error, stream_answer_only
        from app.tracing import create_trace, create_span, end_span, active_trace_var, supervisor_span_var, flush_traces
        from app.config import OPENROUTER_MODEL, SHOW_AGENT_PROGRESS
        
        # 1. Initialize trace and parent supervisor span
        trace = create_trace(
            name="travel_plan_request",
            input=params,
            metadata={
                "workflow": "multi_agent_travel_guide",
                "model": OPENROUTER_MODEL,
                "source": params.get("source"),
                "destination": params.get("destination"),
                "days": params.get("days"),
                "people": params.get("people"),
                "travel_style": params.get("travel_style"),
                "endpoint_used": endpoint
            }
        )
        
        super_span_data = create_span(name="supervisor_agent", input=params)
        token = None
        if super_span_data:
            token = supervisor_span_var.set(super_span_data)
            
        yield format_sse("start", {"message": "Generating your travel plan..."})
        if SHOW_AGENT_PROGRESS:
            yield create_progress_event("supervisor", "started")
        
        agents_used = []
        
        try:
            # Check if we have free-form user query vs pre-extracted parameters
            user_message = params.get("user_message")
            
            if user_message:
                # Call supervisor analyze
                analysis = self.analyze_query(user_message, endpoint=endpoint)
                
                if SHOW_AGENT_PROGRESS:
                    yield create_progress_event("supervisor", "completed")
                
                # If not planning and no specific agents matched, default to general chatbot
                if not analysis.get("is_planning") and not analysis.get("agents_to_run"):
                    res = self.generate_response(user_message)
                    logger.info("Streaming chatbot response...")
                    async for chunk in stream_answer_only(res):
                        yield chunk
                        
                    yield format_sse("final", {"trace_id": trace.trace_id if trace else None})
                    yield format_sse("done", {"status": "completed"})
                    return

                # If planning but critical details are missing, return the follow-up question
                follow_up = analysis.get("follow_up_question", "")
                extracted_params = analysis.get("extracted_params", {})
                if analysis.get("is_planning") and (not extracted_params.get("destination") or follow_up):
                    if not follow_up:
                        follow_up = "Which city would you like to travel to?"
                    logger.info("Streaming follow-up question...")
                    async for chunk in stream_answer_only(follow_up):
                        yield chunk
                        
                    yield format_sse("final", {"trace_id": trace.trace_id if trace else None})
                    yield format_sse("done", {"status": "completed"})
                    return
                    
                # We have valid parameters, proceed to planning
                params = {
                    "source": extracted_params.get("source") or "Delhi",
                    "destination": extracted_params.get("destination"),
                    "days": extracted_params.get("days") or 3,
                    "people": extracted_params.get("people") or 2,
                    "budget": extracted_params.get("budget") or "15000",
                    "interests": extracted_params.get("interests") or "general sightseeing",
                    "travel_style": extracted_params.get("travel_style") or "medium",
                    "food_preference": extracted_params.get("food_preference"),
                    "travel_date": params.get("travel_date") or "2026-07-10"
                }
                agents_to_run = analysis.get("agents_to_run", [])
            else:
                # Pre-extracted parameters endpoint
                if SHOW_AGENT_PROGRESS:
                    yield create_progress_event("supervisor", "completed")
                agents_to_run = ["destination", "weather", "transport", "hotel", "food", "budget", "itinerary", "booking_link", "safety"]

            # Initialize dynamically to avoid circular imports
            from app.agents.weather_agent import WeatherAgent
            from app.agents.destination_agent import DestinationAgent
            from app.agents.transport_agent import TransportAgent
            from app.agents.hotel_agent import HotelAgent
            from app.agents.food_agent import FoodAgent
            from app.agents.budget_agent import BudgetAgent
            from app.agents.itinerary_agent import ItineraryAgent
            from app.agents.booking_link_agent import BookingLinkAgent
            from app.agents.safety_agent import SafetyAgent

            # Prepare agents mapping
            agents_map = {
                "destination": DestinationAgent(),
                "weather": WeatherAgent(),
                "transport": TransportAgent(),
                "hotel": HotelAgent(),
                "food": FoodAgent(),
                "budget": BudgetAgent(),
                "itinerary": ItineraryAgent(),
                "booking_link": BookingLinkAgent(),
                "safety": SafetyAgent()
            }

            # Sequential agent execution order
            agent_order = ["destination", "weather", "transport", "hotel", "food", "budget", "itinerary", "booking_link", "safety"]
            agent_outputs = {}
            
            source_val = params.get("source", "Delhi")
            dest_val = params.get("destination")
            days_val = int(params.get("days", 3))
            people_val = int(params.get("people", 2))
            budget_val = params.get("budget", "15000")
            interests_val = params.get("interests", "general sightseeing")
            style_val = params.get("travel_style", "medium")
            food_val = params.get("food_preference")
            date_val = params.get("travel_date") or "2026-07-10"

            # Headers corresponding to agent names
            agent_headers = {
                "weather": "## 2. Weather",
                "transport": "## 3. Best Transport Options",
                "hotel": "## 4. Stay Recommendations",
                "destination": "## 5. Places to Visit",
                "food": "## 6. Food Suggestions",
                "itinerary": "## 7. Day-wise Itinerary",
                "budget": "## 8. Budget Estimate",
                "booking_link": "## 9. Booking Links",
                "safety": "## 11. Safety Tips"
            }

            # Stream plan summary header immediately
            summary_header = (
                f"# Ready-to-Go Travel Plan\n\n"
                f"## 1. Trip Summary\n"
                f"- **Route**: {source_val} to {dest_val}\n"
                f"- **Duration**: {days_val} Days\n"
                f"- **Travelers**: {people_val} People\n"
                f"- **Budget**: {budget_val} INR\n"
                f"- **Style**: {style_val.capitalize()}\n"
                f"- **Interests**: {interests_val}\n"
                f"- **Food Preference**: {food_val if food_val else 'None'}\n\n"
            )
            async for chunk in stream_answer_only(summary_header):
                yield chunk

            # 1. Kick off Batch 1 agents (independent agents) in parallel
            tasks = {}
            from app.tracing import copy_context_to_thread
            
            def run_agent_sync(name: str, instance, **kwargs):
                return instance.run(**kwargs)

            for agent_name in agent_order:
                if agent_name == "itinerary":
                    continue  # itinerary has dependencies, runs in Batch 2
                if agent_name not in agents_to_run:
                    continue
                if not dest_val:
                    continue
                
                # Setup parameters
                if agent_name == "destination":
                    kwargs = {"destination": dest_val, "interests": interests_val, "days": days_val}
                elif agent_name == "weather":
                    kwargs = {"destination": dest_val}
                elif agent_name == "transport":
                    kwargs = {"source": source_val, "destination": dest_val}
                elif agent_name == "hotel":
                    kwargs = {"destination": dest_val, "budget": budget_val, "travelers": people_val, "travel_style": style_val}
                elif agent_name == "food":
                    kwargs = {"destination": dest_val, "food_preference": food_val}
                elif agent_name == "budget":
                    kwargs = {"source": source_val, "destination": dest_val, "days": days_val, "people": people_val, "travel_style": style_val}
                elif agent_name == "booking_link":
                    kwargs = {"source": source_val, "destination": dest_val, "date": date_val, "people": people_val, "budget": budget_val, "travel_style": style_val}
                elif agent_name == "safety":
                    kwargs = {"destination": dest_val}
                else:
                    continue

                if SHOW_AGENT_PROGRESS:
                    yield create_progress_event(agent_name, "started")
                
                tasks[agent_name] = asyncio.create_task(
                    asyncio.to_thread(copy_context_to_thread, run_agent_sync, agent_name, agents_map[agent_name], **kwargs)
                )

            # Wrapper to couple agent execution with its identifier name
            async def run_and_name_agent(name: str, task):
                try:
                    res = await task
                    return name, res, None
                except Exception as e:
                    return name, None, e

            # Create set of pending tasks for all Batch 1 concurrent executions
            pending_tasks = set()
            for name, task in tasks.items():
                pending_tasks.add(asyncio.create_task(run_and_name_agent(name, task)))

            itinerary_started = False

            # Free-for-all out-of-order event loop
            while pending_tasks:
                done, pending_tasks = await asyncio.wait(pending_tasks, return_when=asyncio.FIRST_COMPLETED)
                for task in done:
                    name, res, err = await task
                    
                    if err:
                        err_msg = f"{name.capitalize()} Agent failed: {str(err)}"
                        logger.warning(err_msg)
                        yield format_sse("error", {"agent": name, "message": err_msg})
                        agent_outputs[name] = f"Error executing agent: {str(err)}"
                        if SHOW_AGENT_PROGRESS:
                            yield create_progress_event(name, "failed")
                    else:
                        if "Error" in res or "Failed" in res:
                            yield format_sse("error", {"agent": name, "message": f"{name.capitalize()} Agent had a partial failure: {res}"})
                        
                        agent_outputs[name] = res
                        agents_used.append(name)
                        if SHOW_AGENT_PROGRESS:
                            yield create_progress_event(name, "completed")
                        
                        # Stream the finished agent's output immediately
                        header = agent_headers.get(name, f"## {name.capitalize()}")
                        formatted_content = f"{header}\n{res}\n\n"
                        async for chunk in stream_answer_only(formatted_content):
                            yield chunk

                    # Dynamic Batch 2 resolution: trigger Itinerary when its 4 dependencies are resolved
                    if "itinerary" in agents_to_run and not itinerary_started:
                        deps = ["destination", "weather", "hotel", "food"]
                        active_deps = [d for d in deps if d in agents_to_run]
                        if all(d in agent_outputs for d in active_deps):
                            context_parts = []
                            if "destination" in agent_outputs:
                                context_parts.append(f"Attractions: {agent_outputs['destination']}")
                            if "weather" in agent_outputs:
                                context_parts.append(f"Weather: {agent_outputs['weather']}")
                            if "hotel" in agent_outputs:
                                context_parts.append(f"Hotel Areas: {agent_outputs['hotel']}")
                            if "food" in agent_outputs:
                                context_parts.append(f"Food Areas: {agent_outputs['food']}")
                            itinerary_context = "\n\n".join(context_parts)
                            
                            if SHOW_AGENT_PROGRESS:
                                yield create_progress_event("itinerary", "started")
                            
                            raw_itin_task = asyncio.create_task(
                                asyncio.to_thread(copy_context_to_thread, run_agent_sync, "itinerary", agents_map["itinerary"], destination=dest_val, days=days_val, interests=interests_val, travel_style=style_val, context=itinerary_context)
                            )
                            # Wrap and add to pending set dynamically
                            wrapped_itin_task = asyncio.create_task(run_and_name_agent("itinerary", raw_itin_task))
                            pending_tasks.add(wrapped_itin_task)
                            itinerary_started = True

            # Stream Packing Checklist (10) and Final Checklist (12) directly to client
            checklist_text = (
                "## 10. Packing Checklist\n"
                "- Comfortable walking shoes\n"
                "- Weather-appropriate clothing\n"
                "- Universal adapter and chargers\n"
                "- Personal medications and basic first aid\n"
                "- Toiletries and sunscreen\n"
                "- Important travel documents and ID proofs\n\n"
                "## 12. Final Checklist Before Booking\n"
                "- Verify train/bus/flight timing\n"
                "- Check hotel reviews\n"
                "- Confirm cancellation policy\n"
                "- Check weather one day before travel\n"
                "- Keep ID proof\n"
                "- Save offline maps\n"
                "- Keep emergency cash\n"
            )
            async for chunk in stream_answer_only(checklist_text):
                yield chunk

            trace_id = trace.trace_id if trace else None
            yield format_sse("final", {"trace_id": trace_id})
            yield format_sse("done", {"status": "completed"})
            
        except Exception as e:
            logger.error(f"Error in streaming supervisor workflow: {e}")
            yield format_sse("error", {"agent": "workflow", "message": str(e)})
        finally:
            if super_span_data:
                end_span(super_span_data)
            if token:
                supervisor_span_var.reset(token)
            
            # End trace root span
            from app.tracing import active_trace_var
            root_data = active_trace_var.get()
            if root_data:
                end_span(root_data)
                
            flush_traces()


